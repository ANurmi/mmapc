import xml.etree.ElementTree as ET
from pathlib import Path, PurePosixPath
from textwrap import dedent

import pytest

from mmapc_src import lint
from mmapc_src.cli import main
from mmapc_src.diagnostics import Diagnostics
from mmapc_src.targets import ipxact
from mmapc_src.targets.options import TargetOptions

REPO_SRC = Path(__file__).resolve().parent.parent / "src"
# The official IEEE 1685-2022 schema set (index.xsd and the files it includes), from
# http://www.accellera.org/XMLSchema/IPXACT/1685-2022/. Schema validation is skipped
# unless it and lxml are present.
IPXACT_XSD = Path(__file__).resolve().parent / "data" / "ipxact-1685-2022" / "index.xsd"

NS = {"ipxact": ipxact.NS}
# Child element order in the schema (only the elements we emit).
COMPONENT_ORDER = ["vendor", "library", "name", "version", "description", "memoryMaps"]
BLOCK_ORDER = ["name", "description", "baseAddress", "typeIdentifier", "range", "width"]
RFILE_ORDER = ["name", "description", "addressOffset", "typeIdentifier", "range"]


def generate(top: Path, name: str = "soc") -> tuple[str | None, Diagnostics]:
    mm, diags = lint(top)
    assert diags.errors == [], [d.render() for d in diags.items]
    gen = Diagnostics()
    out = ipxact.generate(mm, gen, TargetOptions(name=name))
    assert set(out) <= {PurePosixPath(f"{name}.ipxact.xml")}
    return next(iter(out.values()), None), gen


def write(tmp_path: Path, regions: str, bits: int = 32) -> Path:
    body = "\n".join("    " + line for line in dedent(regions).splitlines())
    path = tmp_path / "top.yml"
    path.write_text(f"memory:\n  address_bits: {bits}\n  regions:\n{body}\n")
    return path


def local(el: ET.Element) -> str:
    return el.tag.split("}")[1]


def text(el: ET.Element, tag: str) -> str | None:
    return el.findtext(f"ipxact:{tag}", namespaces=NS)


def parse_int(expr: str) -> int:
    assert expr.startswith("'h"), expr
    return int(expr[2:], 16)


def memory_map(xml: str) -> ET.Element:
    root = ET.fromstring(xml)
    assert root.tag == f"{{{ipxact.NS}}}component"
    assert [local(c) for c in root] == COMPONENT_ORDER
    maps = root.findall("ipxact:memoryMaps/ipxact:memoryMap", NS)
    assert len(maps) == 1
    return maps[0]


def check_order(el: ET.Element, order: list[str]) -> None:
    tags = [local(c) for c in el if local(c) != "registerFile"]
    assert tags == [t for t in order if t in tags], tags
    # Register files come after the block's/file's own elements.
    kinds = [local(c) == "registerFile" for c in el]
    assert kinds == sorted(kinds)


def flatten(xml: str) -> dict[str, dict]:
    """Dotted path -> absolute start, range, typeIdentifier and description of each element,
    checking element order on the way."""
    out: dict[str, dict] = {}

    def visit(el: ET.Element, path: str, start: int) -> None:
        out[path] = {
            "start": start,
            "range": parse_int(text(el, "range")),
            "type": text(el, "typeIdentifier"),
            "description": text(el, "description"),
        }
        for rf in el.findall("ipxact:registerFile", NS):
            check_order(rf, RFILE_ORDER)
            visit(rf, f"{path}.{text(rf, 'name')}", start + parse_int(text(rf, "addressOffset")))

    mmap = memory_map(xml)
    assert [local(c) for c in mmap][-1] == "addressUnitBits"
    for block in mmap.findall("ipxact:addressBlock", NS):
        check_order(block, BLOCK_ORDER)
        visit(block, text(block, "name"), parse_int(text(block, "baseAddress")))
    return out


def validate_with_schema(xml: str) -> None:
    etree = pytest.importorskip("lxml.etree")
    if not IPXACT_XSD.exists():
        pytest.skip(f"{IPXACT_XSD} not present")
    schema = etree.XMLSchema(etree.parse(str(IPXACT_XSD)))
    assert schema.validate(etree.fromstring(xml.encode())), schema.error_log


def test_repo_component():
    xml, diags = generate(REPO_SRC / "top.yml", name="zeroheti")
    assert diags.items == []
    assert xml.startswith(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by mmapc from top.yml. Do not edit. -->\n<ipxact:component"
    )
    root = ET.fromstring(xml)
    assert [text(root, t) for t in ("vendor", "library", "name", "version")] == [
        "mmapc", "mmapc", "zeroheti", "1.0",
    ]  # fmt: skip
    regions = flatten(xml)
    # Every region, nested as in the sources, at the address mmapc resolved.
    mm, _ = lint(REPO_SRC / "top.yml")
    expected = {r.qualname: (r.start, r.end - r.start, r.name) for r in mm.walk()}
    assert {p: (v["start"], v["range"], v["description"]) for p, v in regions.items()} == expected
    assert list(regions)[:4] == ["core", "core.dbg", "core.imem", "core.dmem"]  # address order
    assert regions["ext"]["range"] == 0xFFEF0000
    # Nothing in the repo map is replicated.
    assert all(v["type"] is None for v in regions.values())
    block = memory_map(xml).find("ipxact:addressBlock", NS)
    assert text(block, "baseAddress") == "'h00000000" and text(block, "width") == "32"


def test_repo_component_matches_schema():
    xml, _ = generate(REPO_SRC / "top.yml", name="zeroheti")
    validate_with_schema(xml)


def test_replicated_subsystem_shares_type_identifiers(replicated_map):
    xml, diags = generate(replicated_map)
    assert diags.items == []
    regions = flatten(xml)
    assert {p: v["type"] for p, v in regions.items()} == {
        "sub_a": "sub_a", "sub_a.uart": None, "sub_a.dma": "dma", "sub_a.dma.ctrl": None,
        "sub_b": "sub_a", "sub_b.uart": None, "sub_b.dma": "dma", "sub_b.dma.ctrl": None,
        "rom": None,
    }  # fmt: skip
    assert regions["sub_b.dma.ctrl"]["start"] == 0x1100
    validate_with_schema(xml)


def test_type_identifier_needs_identical_layout(tmp_path):
    xml, _ = generate(
        write(
            tmp_path,
            """\
            - id: a
              name: A
              start: 0x000
              size: 0x100
              children:
                - { id: x, name: X, start: 0x000, size: 8 }
            - id: b
              name: B
              start: 0x100
              size: 0x100
              children:
                - { id: x, name: X, start: 0x110, size: 8 }   # other offset
            - id: c
              name: C
              start: 0x200
              size: 0x80                                      # other range
              children:
                - { id: x, name: X, start: 0x200, size: 8 }
            - id: d
              name: D
              start: 0x300
              size: 0x100
              children:
                - { id: x, name: Other name, start: 0x300, size: 8 }   # same layout as a
            """,
            bits=16,
        )
    )
    types = {p: v["type"] for p, v in flatten(xml).items() if "." not in p}
    assert types == {"a": "a", "b": None, "c": None, "d": "a"}


def test_escaping_and_wide_addresses(tmp_path):
    xml, diags = generate(
        write(
            tmp_path,
            """\
            - { id: a, name: "R&D <lab>\\n\\"x\\"", start: 0x10_0000_0000, size: 4K }
            """,
            bits=40,
        )
    )
    assert diags.items == []
    block = memory_map(xml).find("ipxact:addressBlock", NS)
    assert text(block, "description") == 'R&D <lab> "x"'
    assert text(block, "baseAddress") == "'h1000000000"
    assert text(block, "width") == "64"
    validate_with_schema(xml)


@pytest.mark.parametrize("name", ["my soc", "1soc", "a:b"])
def test_bad_component_name(tmp_path, name):
    xml, diags = generate(write(tmp_path, "- { id: a, name: A, start: 0, size: 4 }"), name)
    assert xml is None
    assert diags.codes() == ["ipxact-bad-name"]


def test_cli_writes_component(tmp_path, capsys):
    argv = ["-t", "ipxact", "-n", "zeroheti", "-o", str(tmp_path), str(REPO_SRC / "top.yml")]
    assert main(argv) == 0
    assert [p.name for p in tmp_path.iterdir()] == ["zeroheti.ipxact.xml"]
    assert "zeroheti.ipxact.xml" in capsys.readouterr().err
