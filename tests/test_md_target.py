from pathlib import Path, PurePosixPath
from textwrap import dedent

from mmapc_src import lint
from mmapc_src.cli import main
from mmapc_src.diagnostics import Diagnostics
from mmapc_src.targets import md
from mmapc_src.targets.options import TargetOptions

REPO_SRC = Path(__file__).resolve().parent.parent / "src"


def generate(top: Path, name: str = "soc") -> str:
    mm, diags = lint(top)
    assert diags.errors == [], [d.render() for d in diags.items]
    gen = Diagnostics()
    out = md.generate(mm, gen, TargetOptions(name=name))
    assert gen.items == []
    assert list(out) == [PurePosixPath(f"{name}_memory_map.md")]
    return out[PurePosixPath(f"{name}_memory_map.md")]


def write(tmp_path: Path, regions: str, bits: int = 32) -> Path:
    body = "\n".join("    " + line for line in dedent(regions).splitlines())
    path = tmp_path / "top.yml"
    path.write_text(f"memory:\n  address_bits: {bits}\n  regions:\n{body}\n")
    return path


def cells(row: str) -> list[str]:
    """Split a GFM table row on unescaped pipes."""
    assert row.startswith("| ") and row.endswith(" |"), row
    out, cur, i = [], "", 1
    while i < len(row) - 1:
        if row[i] == "\\":
            cur += row[i : i + 2]
            i += 2
            continue
        if row[i] == "|":
            out.append(cur.strip())
            cur = ""
        else:
            cur += row[i]
        i += 1
    return [*out, cur.strip()]


def tables(text: str) -> list[list[list[str]]]:
    """Every table in the document as rows of cells (header and delimiter row included)."""
    out, cur = [], []
    for line in text.splitlines() + [""]:
        if line.startswith("|"):
            cur.append(cells(line))
        elif cur:
            out.append(cur)
            cur = []
    return out


def test_repo_document():
    text = generate(REPO_SRC / "top.yml", name="top")
    assert text.startswith("# top memory map\n\nGenerated by mmapc from `top.yml`. Do not edit.\n")
    assert "32-bit address space. End addresses are inclusive." in text
    assert text.endswith("|\n")
    # Top level, then one section per region with children, in address order.
    assert [line for line in text.splitlines() if line.startswith("#")] == [
        "# top memory map", "## Core (`core`)", "## Peripherals (`periph`)",
    ]  # fmt: skip
    assert "`0x00033000` to `0x000B2FFF`, 512K." in text
    top, core, periph = tables(text)
    assert top[0] == ["Name", "ID", "Start", "End", "Size"]
    assert [row[1] for row in top[2:]] == [
        "`core`", "`bootrom`", "`periph`", "`intc`", "`mbx`", "`ext`",
    ]  # fmt: skip
    assert top[-1] == [
        "External Address Space", "`ext`", "`0x00110000`", "`0xFFFFFFFF`", "0xFFEF0000",
    ]  # fmt: skip
    assert [row[1] for row in core[2:]] == ["`dbg`", "`imem`", "`dmem`"]
    assert periph[2] == ["UART", "`uart`", "`0x00033000`", "`0x00033007`", "8"]
    for table in (top, core, periph):
        assert all(len(row) == 5 for row in table)


def test_nested_sections_and_address_order(tmp_path):
    text = generate(
        write(
            tmp_path,
            """\
            - id: hi
              name: High
              start: 0x8000
              children:
                - id: mid
                  name: Mid
                  start: 0x9000
                  size: 4K
                  children:
                    - { id: leaf, name: Leaf, size: 16 }
            - { id: lo, name: Low, start: 0, size: 4K }
            """,
            bits=16,
        )
    )
    assert [line for line in text.splitlines() if line.startswith("#")] == [
        "# soc memory map", "## High (`hi`)", "### Mid (`mid`)",
    ]  # fmt: skip
    top, hi, mid = tables(text)
    assert [row[1] for row in top[2:]] == ["`lo`", "`hi`"]
    assert top[3][2:] == ["`0x8000`", "`0xFFFF`", "32K"]  # runs to the top of the space
    assert mid[2] == ["Leaf", "`leaf`", "`0x9000`", "`0x900F`", "16"]  # implicit start


def test_heading_depth_is_capped(tmp_path):
    lines = []
    for depth in range(7):
        pad = "  " * (2 * depth)
        lines += [f"{pad}- id: r{depth}", f"{pad}  name: R{depth}", f"{pad}  start: 0",
                  f"{pad}  size: 4K", f"{pad}  children:"]  # fmt: skip
    lines.append("  " * 14 + "- { id: leaf, name: Leaf, size: 4 }")
    text = generate(write(tmp_path, "\n".join(lines)))
    headings = [line.split(" ")[0] for line in text.splitlines() if line.startswith("#")]
    assert headings == ["#", "##", "###", "####", "#####", "######", "######", "######"]


def test_special_characters_are_escaped(tmp_path):
    text = generate(
        write(tmp_path, "- { id: a, name: 'A | B *x* <y> `z` \\ [l]', start: 0, size: 4 }")
    )
    (top,) = tables(text)
    assert top[2][0] == r"A \| B \*x\* \<y\> \`z\` \\ \[l\]"
    assert len(top[2]) == 5


def test_escape():
    assert md.escape("Plain Text 1") == "Plain Text 1"
    assert md.escape("a_b#c~d") == r"a\_b\#c\~d"
    assert md.escape("two\nlines") == "two lines"


def test_cli_writes_markdown(tmp_path, capsys):
    assert main(["-t", "md", "-n", "zeroheti", "-o", str(tmp_path), str(REPO_SRC / "top.yml")]) == 0
    assert [p.name for p in tmp_path.iterdir()] == ["zeroheti_memory_map.md"]
    assert (tmp_path / "zeroheti_memory_map.md").read_text().startswith("# zeroheti memory map")
    captured = capsys.readouterr()
    assert captured.out == ""
    assert captured.err.count("mmapc: wrote") == 1


def test_replicated_ids_are_qualified_in_headings(replicated_map):
    text = generate(replicated_map)
    assert "## Subsystem A (`sub_a`)" in text
    assert "### DMA (`sub_a.dma`)" in text
    assert "### DMA (`sub_b.dma`)" in text
    # Tables keep plain ids: the heading above says whose children they are.
    assert "| UART | `uart` | `0x1000` | `0x10FF` | 256 |" in text
