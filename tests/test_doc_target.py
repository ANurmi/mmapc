REPO_SRC = Path(__file__).resolve().parent.parent / "src"
MEMMAP = shutil.which("memmap")
needs_memmap = pytest.mark.skipif(MEMMAP is None, reason="memmap not installed")


def generate(
    top: Path, directives: Path | None = None, name: str = "soc"
) -> tuple[str | None, Diagnostics]:
    mm, diags = lint(top)
    assert diags.errors == [], [d.render() for d in diags.items]
    gen = Diagnostics()
    out = doc.generate(mm, gen, TargetOptions(name=name, directives=directives))
    assert set(out) <= {PurePosixPath(f"{name}_memmap.yaml")}
    return next(iter(out.values()), None), gen


def write(tmp_path: Path, regions: str, bits: int = 32) -> Path:
    body = "\n".join("    " + line for line in dedent(regions).splitlines())
    path = tmp_path / "top.yml"
    path.write_text(f"memory:\n  address_bits: {bits}\n  regions:\n{body}\n")
    return path


def directives(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "doc.yml"
    path.write_text(dedent(text))
    return path


def memmap(*args: str, cwd: Path) -> dict:
    """Run memmap with --json and return its result object."""
    proc = subprocess.run([MEMMAP, *args, "--json"], cwd=cwd, capture_output=True, text=True)
    return json.loads(proc.stdout)


def regions_by_id(regions: list[dict]) -> dict[str, dict]:
    out = {}
    for r in regions:
        out[r["id"]] = r
        out.update(regions_by_id(r.get("children", [])))
    return out


# -- translation ---------------------------------------------------------------------------


def test_repo_translation():
    text, diags = generate(REPO_SRC / "top.yml", name="top")
    assert diags.items == []
    assert text.startswith("# Generated by mmapc from top.yml. Do not edit.\n")
    cfg = yaml.safe_load(text)
    assert cfg["version"] == 1
    assert cfg["figure"] == {"title": "top memory map"}
    assert cfg["memory"]["address_bits"] == 32
    # Top level and children in address order, with explicit starts and sizes.
    assert [r["id"] for r in cfg["memory"]["regions"]] == [
        "core", "bootrom", "periph", "intc", "mbx", "ext",
    ]  # fmt: skip
    assert "{id: bootrom, name: BootROM, start: 0x00030000, size: 12K}" in text
    assert "{id: uart, name: UART, start: 0x00033000, size: 8}" in text
    # A region without a size runs to the end of the address space.
    assert "{id: ext, name: External Address Space, start: 0x00110000, size: 0xFFEF0000}" in text
    assert cfg["view"] == {"expand": ["core", "periph"]}


def test_implicit_starts_and_sizes_are_resolved(tmp_path):
    text, _ = generate(
        write(
            tmp_path,
            """\
            - id: p
              name: P
              start: 0x1000
              size: 4K
              children:
                - { id: b, name: B, start: 0x1800, size: 0x100 }
                - { id: a, name: A, size: 0x100 }
                - { id: c, name: C, start: 0x1A00 }
            """,
            bits=16,
        )
    )
    cfg = yaml.safe_load(text)
    kids = cfg["memory"]["regions"][0]["children"]
    # A is placed after its preceding sibling B in source order; C runs to the parent's end.
    assert [(k["id"], k["start"], k["size"]) for k in kids] == [
        ("b", 0x1800, 0x100), ("a", 0x1900, 0x100), ("c", 0x1A00, 0x600),
    ]  # fmt: skip


def test_size_formatting():
    assert doc._size(8) == 8
    assert doc._size(1023) == 1023
    assert doc._size(1024) == "1K"
    assert doc._size(1536) == 0x600
    assert doc._size(512 << 10) == "512K"
    assert doc._size(1 << 20) == "1M"
    assert doc._size(8 << 30) == "8G"
    assert doc._size(1 << 40) == 1 << 40


def test_wide_addresses_and_top_of_space(tmp_path):
    text, _ = generate(
        write(tmp_path, "- { id: hi, name: Hi, start: 0x8000000000 }", bits=40), name="w"
    )
    assert "{id: hi, name: Hi, start: 0x8000000000, size: 512G}" in text


def test_multiline_name_stays_on_one_line(tmp_path):
    d = directives(tmp_path, 'regions:\n  a: { name: "Line one\\nLine two" }\n')
    text, _ = generate(write(tmp_path, "- { id: a, name: A, start: 0, size: 4 }"), d)
    assert 'name: "Line one\\nLine two"' in text


