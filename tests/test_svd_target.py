import xml.etree.ElementTree as ET
from pathlib import Path, PurePosixPath
from textwrap import dedent

import pytest

from mmapc_src import lint
from mmapc_src.cli import main
from mmapc_src.diagnostics import Diagnostics
from mmapc_src.targets import svd
from mmapc_src.targets.options import TargetOptions

REPO_SRC = Path(__file__).resolve().parent.parent / "src"
# The official CMSIS-SVD 1.3 schema (Apache-2.0), from ARM-software/CMSIS_5
# CMSIS/Utilities/CMSIS-SVD.xsd. Schema validation is skipped unless it and lxml are present.
SVD_XSD = Path(__file__).resolve().parent / "data" / "CMSIS-SVD.xsd"

# Child element order of <device> and <peripheral> in the schema (only those we emit).
DEVICE_ORDER = ["name", "version", "description", "addressUnitBits", "width", "peripherals"]
PERIPHERAL_ORDER = ["name", "description", "groupName", "baseAddress", "addressBlock"]


def generate(top: Path, name: str = "soc") -> tuple[str | None, Diagnostics]:
    mm, diags = lint(top)
    assert diags.errors == [], [d.render() for d in diags.items]
    gen = Diagnostics()
    out = svd.generate(mm, gen, TargetOptions(name=name))
    assert set(out) <= {PurePosixPath(f"{name}.svd")}
    return next(iter(out.values()), None), gen


def write(tmp_path: Path, regions: str, bits: int = 32) -> Path:
    body = "\n".join("    " + line for line in dedent(regions).splitlines())
    path = tmp_path / "top.yml"
    path.write_text(f"memory:\n  address_bits: {bits}\n  regions:\n{body}\n")
    return path


def peripherals(text: str) -> dict[str, dict]:
    """Peripheral name -> its child elements' text (and `derivedFrom`, `block`)."""
    root = ET.fromstring(text)
    out = {}
    for p in root.find("peripherals"):
        info = {c.tag: c.text for c in p if c.tag != "addressBlock"}
        if p.get("derivedFrom"):
            info["derivedFrom"] = p.get("derivedFrom")
        block = p.find("addressBlock")
        if block is not None:
            info["block"] = {c.tag: c.text for c in block}
        out[info["name"]] = info
    return out


def check_structure(text: str) -> None:
    """The parts of the schema the stdlib can check: element order and required children."""
    root = ET.fromstring(text)
    assert root.tag == "device" and root.get("schemaVersion") == "1.3"
    assert [c.tag for c in root] == DEVICE_ORDER
    periphs = list(root.find("peripherals"))
    assert periphs, "the schema needs at least one peripheral"
    names = [p.findtext("name") for p in periphs]
    assert len(names) == len(set(names))
    for p in periphs:
        tags = [c.tag for c in p]
        assert tags == sorted(tags, key=PERIPHERAL_ORDER.index), tags
        assert "baseAddress" in tags
        base = p.get("derivedFrom")
        if base:  # a base is defined before its derivatives
            assert base in names[: names.index(p.findtext("name"))]
        else:
            block = p.find("addressBlock")
            assert [c.tag for c in block] == ["offset", "size", "usage"]


def validate_with_schema(text: str) -> None:
    etree = pytest.importorskip("lxml.etree")
    if not SVD_XSD.exists():
        pytest.skip(f"{SVD_XSD} not present")
    schema = etree.XMLSchema(etree.parse(str(SVD_XSD)))
    doc = etree.fromstring(text.encode())
    assert schema.validate(doc), schema.error_log


def test_repo_device():
    text, diags = generate(REPO_SRC / "top.yml", name="zeroheti")
    assert diags.items == []
    assert text.startswith(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by mmapc from top.yml. Do not edit. -->\n<device"
    )
    check_structure(text)
    root = ET.fromstring(text)
    assert root.findtext("name") == "zeroheti"
    assert root.findtext("width") == "32"
    ps = peripherals(text)
    # Leaves only, in address order; containers become groups.
    assert list(ps) == [
        "DBG", "IMEM", "DMEM", "BOOTROM", "UART", "MTIMER", "I2C0", "I2C1", "TG", "TQ",
        "CFG", "SPI", "INTC", "MBX", "EXT",
    ]  # fmt: skip
    assert "CORE" not in ps and "PERIPH" not in ps
    assert ps["UART"] == {
        "name": "UART",
        "description": "UART",
        "groupName": "PERIPH",
        "baseAddress": "0x00033000",
        "block": {"offset": "0x0", "size": "0x8", "usage": "registers"},
    }
    assert "groupName" not in ps["BOOTROM"]
    # A region without a size runs to the end of the address space.
    assert ps["EXT"]["baseAddress"] == "0x00110000"
    assert ps["EXT"]["block"]["size"] == "0xFFEF0000"


def test_repo_device_matches_schema():
    text, _ = generate(REPO_SRC / "top.yml", name="zeroheti")
    validate_with_schema(text)


def test_replicated_leaves_are_derived(replicated_map):
    text, diags = generate(replicated_map)
    assert diags.items == []
    check_structure(text)
    ps = peripherals(text)
    assert list(ps) == [
        "SUB_A_UART", "SUB_A_DMA_CTRL", "SUB_B_UART", "SUB_B_DMA_CTRL", "ROM",
    ]  # fmt: skip
    assert ps["SUB_A_DMA_CTRL"]["groupName"] == "SUB_A_DMA"
    # The second instance derives from the first, overriding only what differs.
    assert ps["SUB_B_UART"] == {
        "name": "SUB_B_UART",
        "derivedFrom": "SUB_A_UART",
        "groupName": "SUB_B",
        "baseAddress": "0x1000",
    }
    assert ps["SUB_B_DMA_CTRL"]["derivedFrom"] == "SUB_A_DMA_CTRL"
    assert ps["SUB_B_DMA_CTRL"]["groupName"] == "SUB_B_DMA"
    validate_with_schema(text)


def test_derivation_needs_same_size_and_keeps_differing_description(tmp_path):
    text, _ = generate(
        write(
            tmp_path,
            """\
            - id: a
              name: A
              start: 0x000
              size: 0x100
              children:
                - { id: uart, name: UART, size: 8 }
                - { id: spi,  name: SPI,  size: 8 }
            - id: b
              name: B
              start: 0x100
              size: 0x100
              children:
                - { id: uart, name: Debug UART, size: 8 }
                - { id: spi,  name: SPI,        size: 16 }   # other size: not derived
            """,
            bits=16,
        )
    )
    check_structure(text)
    ps = peripherals(text)
    assert ps["B_UART"]["derivedFrom"] == "A_UART"
    assert ps["B_UART"]["description"] == "Debug UART"
    assert "derivedFrom" not in ps["B_SPI"]
    assert ps["B_SPI"]["block"]["size"] == "0x10"


def test_escaping_and_wide_addresses(tmp_path):
    text, diags = generate(
        write(
            tmp_path,
            """\
            - { id: a, name: "R&D <lab> \\"x\\"", start: 0x10_0000_0000, size: 4K }
            """,
            bits=40,
        )
    )
    assert diags.items == []
    check_structure(text)
    root = ET.fromstring(text)
    assert root.findtext("width") == "64"
    p = peripherals(text)["A"]
    assert p["description"] == 'R&D <lab> "x"'
    assert p["baseAddress"] == "0x1000000000"
    validate_with_schema(text)


def test_name_clash(tmp_path):
    text, diags = generate(
        write(
            tmp_path,
            """\
            - { id: uart, name: A, start: 0, size: 4 }
            - { id: UART, name: B, start: 4, size: 4 }
            """,
        )
    )
    assert text is None
    assert diags.codes() == ["svd-name-clash"]


def test_bad_device_name(tmp_path):
    text, diags = generate(write(tmp_path, "- { id: a, name: A, start: 0, size: 4 }"), "my-soc")
    assert text is None
    assert diags.codes() == ["svd-bad-name"]


def test_empty_map(tmp_path):
    text, diags = generate(write(tmp_path, "[]"))
    assert text is None
    assert diags.codes() == ["svd-empty"]


def test_cli_writes_svd(tmp_path, capsys):
    assert (
        main(["-t", "svd", "-n", "zeroheti", "-o", str(tmp_path), str(REPO_SRC / "top.yml")]) == 0
    )
    assert [p.name for p in tmp_path.iterdir()] == ["zeroheti.svd"]
    assert "zeroheti.svd" in capsys.readouterr().err
