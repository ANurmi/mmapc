"""Markdown target: the memory map as GitHub-flavored Markdown tables.

Writes one `<name>_memory_map.md`: a table of the top-level regions, then a section per region
with children (depth-first, headings nested by depth) holding a table of its children.
Siblings are in address order, and end addresses are inclusive, as in `mmapc -l`.
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath

from ..diagnostics import Diagnostics
from ..model import MemoryMap, Region
from ..render import format_size
from .options import TargetOptions

_HEADER = ["| Name | ID | Start | End | Size |", "| --- | --- | --- | --- | ---: |"]
# Characters with a meaning inside a GFM table cell or inline text.
_SPECIAL = re.compile(r"([\\`*_\[\]<>|#~])")


def escape(text: str) -> str:
    """Escape text for a Markdown table cell or heading; line breaks become spaces."""
    return _SPECIAL.sub(r"\\\1", " ".join(text.split()))


def _ordered(regions: list[Region]) -> list[Region]:
    return sorted(regions, key=lambda r: r.start)


def generate(mm: MemoryMap, diags: Diagnostics, opts: TargetOptions) -> dict[PurePosixPath, str]:
    width = (mm.address_bits + 3) // 4

    def addr(v: int) -> str:
        return f"`0x{v:0{width}X}`"

    def table(regions: list[Region]) -> list[str]:
        rows = [
            f"| {escape(r.name)} | `{r.id}` | {addr(r.start)} | {addr(r.end - 1)} | "
            f"{format_size(r.end - r.start)} |"
            for r in _ordered(regions)
        ]
        return [*_HEADER, *rows]

    top = next(iter(mm.files), None)
    source = f" from `{top.name}`" if top else ""
    lines = [
        f"# {escape(opts.name)} memory map",
        "",
        f"Generated by mmapc{source}. Do not edit.",
        "",
        f"{mm.address_bits}-bit address space. End addresses are inclusive.",
        "",
        *table(mm.regions),
    ]

    def sections(regions: list[Region], depth: int) -> None:
        for r in _ordered(regions):
            if not r.children:
                continue
            level = "#" * min(depth + 2, 6)
            lines.extend(
                [
                    "",
                    f"{level} {escape(r.name)} (`{r.id}`)",
                    "",
                    f"{addr(r.start)} to {addr(r.end - 1)}, {format_size(r.end - r.start)}.",
                    "",
                    *table(r.children),
                ]
            )
            sections(r.children, depth + 1)

    sections(mm.regions, 0)
    return {PurePosixPath(f"{opts.name}_memory_map.md"): "\n".join(lines) + "\n"}
