"""C header target: one header per source file, mirroring the include structure.

`src/top.yml` -> `top.h`, `src/core.yml` -> `core.h`, and so on. A header `#include`s the
headers of the files its source includes. Each region becomes a single base address:

    #define <ID>_BASE 0x...UL  /* <name> */

with <ID> the region id in upper case. Ids need only be unique among siblings; an id used by
more than one region is qualified with its hierarchy instead (`periph.uart` ->
`PERIPH_UART_BASE`). A top-level region with children gets its own paragraph, with its
descendants directly below it. Names that still collide (e.g. only after upper-casing) are
reported as errors.
"""

from __future__ import annotations

import os
import re
from pathlib import Path, PurePosixPath

from ..diagnostics import Diagnostics
from ..model import MemoryMap, Region
from .options import TargetOptions

_U32_MAX = 0xFFFF_FFFF


def _literal(value: int, width: int) -> str:
    return f"0x{value:0{width}X}" + ("ULL" if value > _U32_MAX else "UL")


def _comment(text: str) -> str:
    return text.replace("*/", "* /")


def _guard(rel: PurePosixPath) -> str:
    return "MMAPC_" + re.sub(r"[^A-Za-z0-9]", "_", str(rel)).upper()


def generate(mm: MemoryMap, diags: Diagnostics, opts: TargetOptions) -> dict[PurePosixPath, str]:
    width = (mm.address_bits + 3) // 4
    sources = list(mm.files)
    root = Path(os.path.commonpath([p.parent for p in sources]))

    def header_of(src: Path) -> PurePosixPath:
        return PurePosixPath(src.relative_to(root).with_suffix(".h").as_posix())

    ambiguous = mm.ambiguous_ids()

    def prefix(r: Region) -> str:
        return mm.unique_name(r, "_", ambiguous).upper()

    # Macro prefixes must stay unique after qualifying and upper-casing.
    by_macro: dict[str, Region] = {}
    for r in mm.walk():
        macro = prefix(r)
        if macro in by_macro:
            other = by_macro[macro]
            diags.error(
                "c-name-clash",
                f"regions '{other.qualname}' and '{r.qualname}' both map to C macro prefix "
                f"'{macro}'",
                r.at("id"),
                [(other.at("id"), f"'{other.qualname}' defined here")],
            )
        else:
            by_macro[macro] = r

    # Header names must be unique (e.g. a.yml and a.yaml would both become a.h).
    by_header: dict[PurePosixPath, Path] = {}
    for src in sources:
        h = header_of(src)
        if h in by_header:
            diags.error(
                "c-file-clash",
                f"sources '{by_header[h].name}' and '{src.name}' would both generate '{h}'",
                None,
            )
        by_header.setdefault(h, src)

    if diags.errors:
        return {}

    regions_by_file: dict[Path, list[tuple[int, Region]]] = {src: [] for src in sources}

    def collect(regions: list[Region], depth: int) -> None:
        for r in regions:
            regions_by_file[r.loc.path].append((depth, r))
            collect(r.children, depth + 1)

    collect(mm.regions, 0)

    out: dict[PurePosixPath, str] = {}
    for src in sources:
        rel = header_of(src)
        guard = _guard(rel)
        lines = [
            f"/* Generated by mmapc from {src.relative_to(root).as_posix()}. Do not edit. */",
            f"#ifndef {guard}",
            f"#define {guard}",
        ]
        if mm.files[src]:
            lines.append("")
            for inc in mm.files[src]:
                target = PurePosixPath(
                    os.path.relpath(header_of(inc), rel.parent).replace(os.sep, "/")
                )
                lines.append(f'#include "{target}"')

        entries = regions_by_file[src]
        name_w = max([0] + [len(prefix(r)) + len("_BASE") for _, r in entries])
        prev_top: Region | None = None
        for i, (depth, r) in enumerate(entries):
            # Blank line before the first entry and around top-level regions with children.
            if i == 0:
                lines.append("")
            if depth == 0:
                if prev_top is not None and (r.children or prev_top.children):
                    lines.append("")
                prev_top = r
            macro = f"{prefix(r) + '_BASE':<{name_w}}"
            lines.append(f"#define {macro} {_literal(r.start, width)}  /* {_comment(r.name)} */")
        lines += ["", f"#endif /* {guard} */", ""]
        out[rel] = "\n".join(lines)
    return out
